'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (cb) => {
  const h = (_e, ...a) => cb(...a);
  ipcRenderer.on(ch, h);
  return () => ipcRenderer.removeListener(ch, h);
};

contextBridge.exposeInMainWorld('api', {
  readDir: inv('fs:readDir'),
  stat: inv('fs:stat'),
  exists: inv('fs:exists'),
  isDir: inv('fs:isDir'),
  subdirs: inv('fs:subdirs'),
  watch: inv('fs:watch'),
  icon: inv('fs:icon'),
  thumb: inv('fs:thumb'),
  imageSize: inv('fs:imageSize'),
  readText: inv('fs:readText'),
  mkdir: inv('fs:mkdir'),
  newFile: inv('fs:newFile'),
  rename: inv('fs:rename'),
  symlink: inv('fs:symlink'),
  conflicts: inv('fs:conflicts'),
  transfer: inv('fs:transfer'),
  cancelOp: inv('op:cancel'),
  trash: inv('fs:trash'),
  movePairs: inv('fs:movePairs'),
  del: inv('fs:delete'),
  emptyTrash: inv('fs:emptyTrash'),
  folderStats: inv('fs:folderStats'),
  setAttrs: inv('fs:setAttrs'),
  isHiddenFlag: inv('fs:isHiddenFlag'),
  compress: inv('fs:compress'),
  extract: inv('fs:extract'),
  searchStart: inv('search:start'),
  searchCancel: inv('search:cancel'),
  sysInfo: inv('sys:info'),
  volumes: inv('sys:volumes'),
  eject: inv('sys:eject'),
  open: inv('shell:open'),
  openWith: inv('shell:openWith'),
  reveal: inv('shell:reveal'),
  terminal: inv('shell:terminal'),
  openVSCode: inv('shell:openVSCode'),
  getInfo: inv('shell:getInfo'),
  share: inv('shell:share'),
  beep: inv('shell:beep'),
  privacy: inv('shell:privacy'),
  clipWriteFiles: inv('clip:writeFiles'),
  clipReadFiles: inv('clip:readFiles'),
  clipWriteText: inv('clip:writeText'),
  startDrag: (paths) => ipcRenderer.send('drag:start', paths),
  pickFolder: inv('dlg:pickFolder'),
  confirm: inv('dlg:confirm'),
  getSettings: inv('settings:get'),
  setSettings: inv('settings:set'),
  newWindow: inv('win:new'),
  closeWindow: inv('win:close'),
  toggleMax: inv('win:toggleMax'),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return f.path || ''; } },
  onChanged: on('fs:changed'),
  onOpStart: on('op:start'),
  onOpProgress: on('op:progress'),
  onOpEnd: on('op:end'),
  onSearchResults: on('search:results'),
  onSearchDone: on('search:done'),
  onMenu: on('menu:action'),
  onSettings: on('settings:changed'),
  onTheme: on('theme:changed'),
  onFullscreen: on('win:fullscreen'),
  platform: process.platform,
});
